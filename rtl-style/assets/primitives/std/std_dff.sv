// =============================================================================
// 模块：std_dff
// 功能：无复位、无加载使能的通用寄存器原语，每个clk上升沿无条件装入dnxt。
// 适用：每拍都更新、且下游以有效标志限定使用的数据通路寄存器。上电后输出为X，
//       直到第一次时钟沿装入确定值；控制信号、有效标志和状态寄存器不得使用本原语。
// 端口顺序：(dnxt, qout, clk)是单行位置例化的固定顺序，不得调整。
// =============================================================================
`include "std_defines.svh"

module std_dff #(
    parameter int DW = 32  // 寄存器位宽，单位为bit，合法值为正整数。
) (
    // 下一值输入：每个clk上升沿无条件装入。
    input  wire  [DW-1:0]  dnxt,

    // 寄存器输出：直接来自触发器Q端，没有复位值。
    output logic [DW-1:0]  qout,

    // 时钟：上升沿采样；本原语没有复位端口。
    input  wire            clk
);

    // 寄存器本体：每拍装入下一值；STD_DLY仅在定义STD_SIM_DELAY时展开为#1。
    always_ff @(posedge clk) begin : DFF_PROC
        qout <= `STD_DLY dnxt;
    end

endmodule

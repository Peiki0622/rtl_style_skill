// =============================================================================
// 模块：std_clk_mux2
// 功能：二选一时钟选择器，sel为0输出clk0，为1输出clk1。
// 实现：ASIC流程中本模块是工艺时钟MUX单元的唯一替换点，项目应把模块体替换为
//       工艺库的时钟专用MUX并保持端口不变，避免综合工具把时钟路径映射为普通逻辑门。
// 约束：本单元不做无毛刺切换，只适用于静态选择，如测试时钟与功能时钟的选择，或在
//       两路时钟都已停止时切换。功能运行中动态切换时钟必须使用专门的无毛刺时钟切换电路。
// =============================================================================
`include "std_defines.svh"

module std_clk_mux2 (
    // 候选时钟：clk0在sel为0时输出，clk1在sel为1时输出。
    input  wire   clk0,
    input  wire   clk1,

    // 选择控制：静态信号，只能在两路时钟停止或复位／测试配置阶段改变。
    input  wire   sel,

    // 输出时钟：所选时钟。
    output logic  clk_out
);

    // 时钟选择：静态选择，不处理切换瞬间的毛刺。
    assign clk_out = sel ? clk1 : clk0;

endmodule
